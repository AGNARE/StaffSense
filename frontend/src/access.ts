import { api, type Me } from './api';

/**
 * Права текущего пользователя на клиенте.
 *
 * <p>Единственный источник — {@code GET /api/v1/me}: сервер уже отдаёт список
 * экранов роли ({@code RoleScreens}), поэтому клиент не заводит второй список
 * правил, а только применяет присланный к маршрутам. Меню и страницы читают
 * один и тот же список — экран, которого нет, не откроется и по прямому адресу.
 *
 * <p>Кэш живёт на модуле: маршруты переключаются хешем, без перезагрузки
 * страницы, и запрашивать профиль на каждый переход незачем. Неудачный запрос
 * кэш не задерживает — иначе после восстановления сессии клиент остался бы
 * без прав до F5.
 */
let meRequest: Promise<Me> | null = null;

/** Профиль и разрешённые экраны текущего пользователя (с кэшем на модуле). */
export function loadMe(): Promise<Me> {
  if (!meRequest) {
    const pending = api.me();
    meRequest = pending;
    pending.catch(() => {
      if (meRequest === pending) {
        meRequest = null;
      }
    });
  }
  return meRequest;
}
