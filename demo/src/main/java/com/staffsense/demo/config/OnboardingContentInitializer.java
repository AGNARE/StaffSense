package com.staffsense.demo.config;

import com.staffsense.demo.model.OnboardingArticle;
import com.staffsense.demo.model.OnboardingSection;
import com.staffsense.demo.repository.OnboardingArticleRepository;
import lombok.RequiredArgsConstructor;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.stereotype.Component;

import java.util.List;

/**
 * Наполнение внутреннего портала онбординга демонстрационным содержимым.
 *
 * <p>Выполняется один раз: если статьи уже есть, ничего не меняется.
 * Отдельный компонент (а не часть {@code DataInitializer}), чтобы не раздувать
 * инициализатор демо-данных.
 */
@Component
@Order(20)
@RequiredArgsConstructor
public class OnboardingContentInitializer implements CommandLineRunner {

    private static final Logger log = LoggerFactory.getLogger(OnboardingContentInitializer.class);

    private final OnboardingArticleRepository articleRepository;

    @Override
    public void run(String... args) {
        if (articleRepository.count() > 0) {
            log.info("Onboarding portal already has content, skipping initialization.");
            return;
        }

        List<OnboardingArticle> articles = List.of(
                // ── О компании ───────────────────────────────────────────────
                article(OnboardingSection.ABOUT, "О компании StaffSense", 0,
                        """
                        StaffSense — HR-Tech платформа для управления персоналом и предиктивной
                        HR-аналитики. Мы помогаем руководителям вовремя замечать риск выгорания
                        и увольнения сотрудников и принимать решения на основе данных, а не догадок.

                        Наша миссия — сделать управление людьми прозрачным, справедливым и основанным на фактах.
                        """),
                article(OnboardingSection.ABOUT, "Наши ценности", 1,
                        """
                        1. Честность и открытость — мы говорим о проблемах прямо, а не «по слухам».
                        2. Уважение к времени — встречи начинаются вовремя и заканчиваются результатом.
                        3. Данные вместо мнений — решения подкрепляются цифрами.
                        4. Развитие — каждый сотрудник имеет право на рост и обучение.
                        5. Ответственность — взял задачу, довёл до конца.
                        """),
                article(OnboardingSection.ABOUT, "Как у нас принято", 2,
                        """
                        • Задачи ведутся в канбан-доске StaffSense: TODO → IN_PROGRESS → REVIEW → DONE.
                        • Встречи 1:1 с руководителем — раз в две недели. Пропускать их не принято.
                        • О проблемах сообщаем сразу, а не «когда всё сгорит».
                        • Обратная связь — часть работы, а не критика.
                        """),

                // ── Структура ────────────────────────────────────────────────
                article(OnboardingSection.STRUCTURE, "Структура компании", 0,
                        """
                        Компания состоит из отделов:

                        • Management — стратегия, работа с ключевыми клиентами.
                        • Product — продукт, приоритеты, roadmap.
                        • Engineering — разработка, инфраструктура, качество.
                        • HR — подбор, адаптация, кадровые процессы, well-being.
                        • Sales — продажи и работа с клиентами.
                        • Marketing — продвижение и коммуникации.
                        • Design — пользовательский опыт и визуальный стиль.
                        """),

                // ── Должностные инструкции ───────────────────────────────────
                article(OnboardingSection.RESPONSIBILITIES, "Java-разработчик", 0,
                        """
                        Обязанности:
                        • Разработка серверной логики на Java 21 / Spring Boot.
                        • Проектирование схемы данных и миграций.
                        • Написание тестов и участие в код-ревью.
                        • Оценка задач и соблюдение сроков.

                        Ожидания:
                        • Понимание REST, JPA, SQL.
                        • Аккуратность в работе с чужим кодом.
                        • Готовность объяснять свои решения.
                        """),
                article(OnboardingSection.RESPONSIBILITIES, "QA-инженер", 1,
                        """
                        Обязанности:
                        • Проверка новых функций до релиза.
                        • Ведение чек-листов и тест-кейсов.
                        • Регистрация дефектов с воспроизводимыми шагами.
                        • Участие в приёмке задач.

                        Ожидания:
                        • Внимание к деталям и граничным случаям.
                        • Умение отличать дефект от ожидаемого поведения.
                        """),
                article(OnboardingSection.RESPONSIBILITIES, "Project Manager", 2,
                        """
                        Обязанности:
                        • Планирование и распределение задач в команде.
                        • Ведение канбан-доски и контроль сроков.
                        • Проведение встреч 1:1 с сотрудниками.
                        • Ведение табеля рабочего времени по своей команде.

                        Ожидания:
                        • Видеть риски заранее и сообщать о них.
                        • Не допускать перегрузки сотрудников.
                        """),

                // ── Регламенты ───────────────────────────────────────────────
                article(OnboardingSection.POLICIES, "Отпуска", 0,
                        """
                        Ежегодный оплачиваемый отпуск — 28 календарных дней.
                        Заявление подаётся служебной запиской в разделе «Служебные записки»:
                        сначала её визирует руководитель, затем утверждает HR.
                        Рекомендуется подавать заявление не позднее чем за 14 дней до начала отпуска.
                        """),
                article(OnboardingSection.POLICIES, "Больничные", 1,
                        """
                        О нетрудоспособности нужно сообщить руководителю в первый день.
                        Заявление оформляется служебной запиской типа «Больничный».
                        Утверждённый больничный автоматически отражается в табеле рабочего времени.
                        """),
                article(OnboardingSection.POLICIES, "Удалённая работа", 2,
                        """
                        Удалённая работа возможна по согласованию с руководителем.
                        Дни удалённой работы отмечаются в табеле.
                        Требования: доступность в рабочие часы и участие во встречах.
                        """),
                article(OnboardingSection.POLICIES, "Информационная безопасность", 3,
                        """
                        • Пароль должен быть уникальным; передавать его коллегам запрещено.
                        • Рабочие данные не выгружаются на личные устройства без согласования.
                        • Персональные данные сотрудников — конфиденциальны: доступ к ним
                          ограничен ролями HR и ADMIN и фиксируется в журнале.
                        • О подозрении на инцидент сообщать немедленно.
                        """),

                // ── FAQ ──────────────────────────────────────────────────────
                article(OnboardingSection.FAQ, "Как получить доступы?", 0,
                        """
                        Учётную запись создаёт HR при приёме на работу. Логин — рабочий email.
                        Если доступ не работает, обратитесь в HR или к своему руководителю.
                        """),
                article(OnboardingSection.FAQ, "К кому обращаться по рабочим вопросам?", 1,
                        """
                        • По задачам и приоритетам — к руководителю проекта (PM).
                        • По кадровым вопросам, отпускам, больничным — в HR.
                        • По доступам и техническим сбоям — к руководителю, он эскалирует дальше.
                        """),
                article(OnboardingSection.FAQ, "Что такое прогноз риска увольнения?", 2,
                        """
                        Это вспомогательная оценка, которую система рассчитывает по данным
                        о нагрузке, KPI, удовлетворённости и встречах 1:1.
                        Прогноз носит рекомендательный характер и не является основанием
                        для кадровых решений без участия человека.
                        """),

                // ── Чек-лист новичка ─────────────────────────────────────────
                article(OnboardingSection.CHECKLIST, "Получить рабочую учётную запись", 0,
                        "Логин и временный пароль выдаёт HR. При первом входе пароль рекомендуется сменить."),
                article(OnboardingSection.CHECKLIST, "Пройти инструктаж по информационной безопасности", 1,
                        "Ознакомиться с регламентом «Информационная безопасность» в разделе «Регламенты»."),
                article(OnboardingSection.CHECKLIST, "Познакомиться с командой", 2,
                        "Посмотреть состав команды в разделе «Справочник» и договориться о коротких знакомствах."),
                article(OnboardingSection.CHECKLIST, "Изучить должностную инструкцию", 3,
                        "Найти свою роль в разделе «Должностные инструкции» и уточнить вопросы у руководителя."),
                article(OnboardingSection.CHECKLIST, "Провести первую встречу 1:1", 4,
                        "Запланировать встречу с руководителем в первые две недели."),
                article(OnboardingSection.CHECKLIST, "Взять первую задачу в работу", 5,
                        "Получить задачу на канбан-доске и перевести её в статус «В работе».")
        );

        articleRepository.saveAll(articles);
        log.info("Onboarding portal initialized with {} articles", articles.size());
    }

    private OnboardingArticle article(OnboardingSection section, String title, int order, String content) {
        return OnboardingArticle.builder()
                .section(section)
                .title(title)
                .content(content.strip())
                .orderIndex(order)
                .published(true)
                .build();
    }
}
