package com.staffsense.demo.service.tunduk;

/**
 * Порт доступа к госсистеме «Тундук / Кызмат».
 *
 * <p>Архитектура «порт и адаптер»: бизнес-логика найма зависит только от этого
 * интерфейса, поэтому переход с эмуляции на реальный протокол обмена данными
 * потребует заменить одну реализацию ({@link MockTundukClient}) и не затронет
 * сервисы, контроллеры и шаблоны.
 */
public interface TundukClient {

    /**
     * Запрашивает персональные данные гражданина по ИНН.
     *
     * @param inn ИНН из 14 цифр (формат проверяется до вызова)
     * @return результат обращения: найден / не найден / сервис недоступен
     */
    TundukLookupResult findByInn(String inn);
}
