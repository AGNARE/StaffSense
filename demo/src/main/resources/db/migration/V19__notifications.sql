-- V19: внутрисистемные уведомления.
--
-- Система уже умеет требовать подпись, считать просрочку и показывать
-- баланс отпуска, но узнать об этом можно было только зайдя в неё.
-- Почтовой рассылки в проекте нет и не планировалось, поэтому первый шаг —
-- уведомление внутри интерфейса: колокол со счётчиком и список.
--
-- Таблица, а не сессия: событие должно дождаться человека, даже если он
-- зашёл позже. Прочитанное помечается временем, а не удаляется — история
-- полезна, а «прочитано» обратимо.

CREATE TABLE IF NOT EXISTS public.notification (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    type character varying(40) NOT NULL,
    title character varying(200) NOT NULL,
    message character varying(500),
    link character varying(200),
    read_at timestamp,
    created_at timestamp NOT NULL,
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE,
    CONSTRAINT notification_type_check CHECK (type IN (
        'DOCUMENT_TO_SIGN', 'DOCUMENT_SIGNED', 'MEMO_TO_APPROVE',
        'SIGNATURE_OVERDUE', 'VACATION_GRANTED'
    ))
);

CREATE INDEX IF NOT EXISTS idx_notification_user_unread
    ON public.notification (user_id, read_at);

CREATE INDEX IF NOT EXISTS idx_notification_created
    ON public.notification (created_at DESC);

COMMENT ON TABLE public.notification IS
    'Уведомления сотруднику: подпись, визы, просрочки (внутри системы)';
