-- V8: каталог ИИ-скиллов (эпик E-08, FR-033, UC-016).
--
-- Отдельная вкладка в боковом меню: сотрудник видит список скиллов, у каждого —
-- название, описание и роль, для которой он предназначен (дизайнер, фронтенд,
-- бэкенд и другие). Доступны скачивание файла и ссылка на репозиторий GitHub,
-- если скилл там опубликован. Наполняет каталог роль с правом администрирования.
--
-- Вызов скилла и рекомендации ИИ в объём не входят: по решению заказчика эпик
-- ограничен каталогом (см. лист изменений к ТЗ, раздел 5.2).

CREATE TABLE IF NOT EXISTS public.ai_skill (
    id bigint NOT NULL,
    name character varying(150) NOT NULL,
    description text,
    -- роль, для которой предназначен скилл:
    -- DESIGNER / FRONTEND / BACKEND / QA / PM / ANALYST / OTHER
    target_role character varying(30) NOT NULL,
    -- файл скилла хранится в базе, чтобы скачивание не зависело от файловой системы
    file_name character varying(255),
    content_type character varying(100),
    file_data bytea,
    -- ссылка на репозиторий GitHub; может отсутствовать
    github_url character varying(500),
    published boolean NOT NULL DEFAULT true,
    created_by_id bigint,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

ALTER TABLE public.ai_skill ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.ai_skill_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

ALTER TABLE ONLY public.ai_skill
    ADD CONSTRAINT ai_skill_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.ai_skill
    ADD CONSTRAINT fk_ai_skill_created_by FOREIGN KEY (created_by_id)
        REFERENCES public.users(id);

CREATE INDEX IF NOT EXISTS idx_ai_skill_role ON public.ai_skill (target_role);
