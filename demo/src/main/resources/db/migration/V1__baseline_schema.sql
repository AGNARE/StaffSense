-- Сгенерировано из фактической схемы PostgreSQL 18 (pg_dump --schema-only),
-- созданной Hibernate, поэтому типы точно соответствуют JPA-сущностям.
--
-- На существующей БД эта миграция не выполняется: Flyway помечает её как baseline
-- (spring.flyway.baseline-on-migrate=true, baseline-version=1), и применяются
-- только последующие миграции (V2 — индексы и уникальность, V3 — колонка XAI).

