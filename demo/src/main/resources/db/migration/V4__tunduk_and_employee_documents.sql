-- V4: модуль «Тундук» — личные дела сотрудников и журнал обращений к госсистеме.
--
-- Модуль A концепции (StaffSense_CONCEPT_TUNDUK_ONBOARDING.md):
-- при приёме на работу HR вводит ИНН, система получает персональные данные
-- гражданина (эмуляция ГУ «Тундук / Кызмат») и заполняет личное дело.
--
-- Персональные данные вынесены из users в отдельную таблицу, чтобы:
--   * ограничить доступ (паспорт и ПИН видят только HR/ADMIN);
--   * не раздувать основную таблицу;
--   * иметь возможность обновить данные при смене паспорта.

-- ── Личное дело (1:1 с users) ────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.employee_documents (
    id bigint NOT NULL,
    user_id bigint NOT NULL,
    inn character varying(14) NOT NULL,
    pin character varying(20),
    birth_date date,
    gender character varying(10),
    passport_series character varying(4),
    passport_number character varying(6),
    passport_issued_by character varying(255),
    passport_issue_date date,
    registration_address character varying(500),
    photo_url character varying(500),
    tunduk_verified boolean NOT NULL DEFAULT false,
    verified_at timestamp(6) without time zone,
    -- BR-024: согласие кандидата на обработку персональных данных
    consent_given_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

ALTER TABLE public.employee_documents
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.employee_documents_id_seq
        START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
    );

ALTER TABLE ONLY public.employee_documents
    ADD CONSTRAINT employee_documents_pkey PRIMARY KEY (id);

-- Одно личное дело на сотрудника и один сотрудник на ИНН.
ALTER TABLE ONLY public.employee_documents
    ADD CONSTRAINT uq_employee_documents_user UNIQUE (user_id);
ALTER TABLE ONLY public.employee_documents
    ADD CONSTRAINT uq_employee_documents_inn UNIQUE (inn);

ALTER TABLE ONLY public.employee_documents
    ADD CONSTRAINT fk_employee_documents_user FOREIGN KEY (user_id) REFERENCES public.users(id);

CREATE INDEX IF NOT EXISTS idx_employee_documents_user_id ON public.employee_documents (user_id);
CREATE INDEX IF NOT EXISTS idx_employee_documents_inn ON public.employee_documents (inn);

-- ── Журнал обращений к «Тундук» (аудит персональных данных, BR-026) ───────
CREATE TABLE IF NOT EXISTS public.tunduk_verification_log (
    id bigint NOT NULL,
    inn character varying(14) NOT NULL,
    requested_by_id bigint NOT NULL,
    requested_at timestamp(6) without time zone NOT NULL,
    -- FOUND / NOT_FOUND / INVALID / UNAVAILABLE
    result character varying(20) NOT NULL,
    target_user_id bigint,
    details text
);

ALTER TABLE public.tunduk_verification_log
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.tunduk_verification_log_id_seq
        START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
    );

ALTER TABLE ONLY public.tunduk_verification_log
    ADD CONSTRAINT tunduk_verification_log_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.tunduk_verification_log
    ADD CONSTRAINT fk_tunduk_log_requested_by FOREIGN KEY (requested_by_id) REFERENCES public.users(id);
ALTER TABLE ONLY public.tunduk_verification_log
    ADD CONSTRAINT fk_tunduk_log_target_user FOREIGN KEY (target_user_id) REFERENCES public.users(id);

CREATE INDEX IF NOT EXISTS idx_tunduk_log_inn ON public.tunduk_verification_log (inn);
CREATE INDEX IF NOT EXISTS idx_tunduk_log_requested_at ON public.tunduk_verification_log (requested_at);
