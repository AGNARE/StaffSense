-- V7: учёт участия в опросе (FR-022, ERR-012).
--
-- Зачем нужна таблица: у анонимного опроса ответ не связывается с сотрудником
-- (BR-011), поэтому по таблице ответов нельзя понять, проходил ли сотрудник
-- этот опрос. Из-за этого прямой переход на страницу опроса позволял отвечать
-- повторно и накручивать результаты. Здесь хранится только факт участия, без
-- ответов, поэтому анонимность сохраняется.

CREATE TABLE IF NOT EXISTS public.survey_participation (
    id bigint NOT NULL,
    survey_id bigint NOT NULL,
    user_id bigint NOT NULL,
    submitted_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.survey_participation ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.survey_participation_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

ALTER TABLE ONLY public.survey_participation
    ADD CONSTRAINT survey_participation_pkey PRIMARY KEY (id);

-- Один сотрудник — один ответ на опрос: защита от повторного прохождения.
ALTER TABLE ONLY public.survey_participation
    ADD CONSTRAINT uq_survey_participation_survey_user UNIQUE (survey_id, user_id);

ALTER TABLE ONLY public.survey_participation
    ADD CONSTRAINT fk_survey_participation_survey FOREIGN KEY (survey_id)
        REFERENCES public.surveys(id) ON DELETE CASCADE;
ALTER TABLE ONLY public.survey_participation
    ADD CONSTRAINT fk_survey_participation_user FOREIGN KEY (user_id)
        REFERENCES public.users(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_survey_participation_survey
    ON public.survey_participation (survey_id);
