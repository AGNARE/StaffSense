-- V6: кадровые процессы — табель рабочего времени и служебные записки (модуль C).
--
-- Правила (согласованы заказчиком, BR-027..BR-030):
--   * часы вносит РУКОВОДИТЕЛЬ (PM) по своей команде; сотрудник — только чтение;
--   * HR и ADMIN редактируют табель любой команды;
--   * табель за закрытый (предыдущий) месяц не редактируется;
--   * отчёты: по команде PM и сводный по компании для HR;
--   * служебную записку может подать любой сотрудник; маршрут: PM визирует → HR утверждает;
--   * автор может редактировать и отозвать записку до финального решения;
--   * утверждённый больничный/отпуск учитывается в табеле и в расчёте нагрузки.

-- ── Табель: записи по дням ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.work_schedule (
    id bigint NOT NULL,
    user_id bigint NOT NULL,
    work_date date NOT NULL,
    hours_worked double precision,
    is_remote boolean NOT NULL DEFAULT false,
    is_sick_leave boolean NOT NULL DEFAULT false,
    -- дни отпуска проставляются автоматически из утверждённых служебных записок
    is_vacation boolean NOT NULL DEFAULT false,
    overtime_hours double precision DEFAULT 0,
    -- кто внёс запись (руководитель или HR/ADMIN)
    created_by_id bigint,
    updated_at timestamp(6) without time zone
);

ALTER TABLE public.work_schedule
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.work_schedule_id_seq
        START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
    );

ALTER TABLE ONLY public.work_schedule
    ADD CONSTRAINT work_schedule_pkey PRIMARY KEY (id);

-- Одна запись на сотрудника в день.
ALTER TABLE ONLY public.work_schedule
    ADD CONSTRAINT uq_work_schedule_user_date UNIQUE (user_id, work_date);

ALTER TABLE ONLY public.work_schedule
    ADD CONSTRAINT fk_work_schedule_user FOREIGN KEY (user_id) REFERENCES public.users(id);
ALTER TABLE ONLY public.work_schedule
    ADD CONSTRAINT fk_work_schedule_created_by FOREIGN KEY (created_by_id) REFERENCES public.users(id);

CREATE INDEX IF NOT EXISTS idx_work_schedule_user_date
    ON public.work_schedule (user_id, work_date);

-- ── Табель: закрытие периода (месяца) ────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.work_schedule_period (
    id bigint NOT NULL,
    -- участок закрытия: команда руководителя
    manager_id bigint NOT NULL,
    period_start date NOT NULL,
    period_end date NOT NULL,
    -- OPEN / CLOSED
    status character varying(20) NOT NULL,
    closed_at timestamp(6) without time zone,
    closed_by_id bigint
);

ALTER TABLE public.work_schedule_period
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.work_schedule_period_id_seq
        START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
    );

ALTER TABLE ONLY public.work_schedule_period
    ADD CONSTRAINT work_schedule_period_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.work_schedule_period
    ADD CONSTRAINT uq_work_schedule_period UNIQUE (manager_id, period_start, period_end);

ALTER TABLE ONLY public.work_schedule_period
    ADD CONSTRAINT fk_work_schedule_period_manager FOREIGN KEY (manager_id) REFERENCES public.users(id);
ALTER TABLE ONLY public.work_schedule_period
    ADD CONSTRAINT fk_work_schedule_period_closed_by FOREIGN KEY (closed_by_id) REFERENCES public.users(id);

-- ── Служебные записки ────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.service_memo (
    id bigint NOT NULL,
    user_id bigint NOT NULL,
    -- VACATION / SICK_LEAVE / OTHER
    memo_type character varying(30) NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    reason text,
    -- DRAFT / PENDING_PM / PENDING_HR / APPROVED / REJECTED / CANCELLED
    status character varying(20) NOT NULL,
    pm_decision_by_id bigint,
    pm_decision_at timestamp(6) without time zone,
    hr_decision_by_id bigint,
    hr_decision_at timestamp(6) without time zone,
    rejection_reason text,
    created_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.service_memo
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.service_memo_id_seq
        START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
    );

ALTER TABLE ONLY public.service_memo
    ADD CONSTRAINT service_memo_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.service_memo
    ADD CONSTRAINT fk_service_memo_user FOREIGN KEY (user_id) REFERENCES public.users(id);
ALTER TABLE ONLY public.service_memo
    ADD CONSTRAINT fk_service_memo_pm_decision FOREIGN KEY (pm_decision_by_id) REFERENCES public.users(id);
ALTER TABLE ONLY public.service_memo
    ADD CONSTRAINT fk_service_memo_hr_decision FOREIGN KEY (hr_decision_by_id) REFERENCES public.users(id);

CREATE INDEX IF NOT EXISTS idx_service_memo_user ON public.service_memo (user_id);
CREATE INDEX IF NOT EXISTS idx_service_memo_status ON public.service_memo (status);
