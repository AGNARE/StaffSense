-- V13: маршрут документа — история переходов статусов.
--
-- До этой миграции у документа был только текущий статус: кто и когда
-- перевёл его на следующий шаг, восстановить было нельзя. Экран «Карточка
-- документа» требует историю статусов, а экран «Входящие и маршруты» —
-- понимание, на каком шаге документ стоит сейчас.
--
-- Пишем актора ссылкой (actor_id): в отличие от журнала администратора,
-- сотрудники не удаляются, а карточка должна показывать имя того, кто
-- согласовал. from_status допускает NULL — это запись о регистрации,
-- когда предыдущего состояния ещё нет.
--
-- Существующие миграции не изменяются: таблица добавляется отдельным шагом.

CREATE TABLE IF NOT EXISTS public.document_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL,
    from_status character varying(30),
    to_status character varying(30) NOT NULL,
    actor_id bigint,
    comment character varying(500),
    created_at timestamp NOT NULL,
    CONSTRAINT doc_history_from_status_check CHECK (
        from_status IS NULL OR from_status IN ('DRAFT', 'ON_APPROVAL', 'APPROVED', 'ARCHIVED')
    ),
    CONSTRAINT doc_history_to_status_check CHECK (
        to_status IN ('DRAFT', 'ON_APPROVAL', 'APPROVED', 'ARCHIVED')
    ),
    CONSTRAINT fk_doc_history_document FOREIGN KEY (document_id)
        REFERENCES public.document(id) ON DELETE CASCADE,
    CONSTRAINT fk_doc_history_actor FOREIGN KEY (actor_id)
        REFERENCES public.users(id)
);

-- Карточка всегда читает историю одного документа в хронологическом порядке.
CREATE INDEX IF NOT EXISTS idx_document_status_history_doc
    ON public.document_status_history (document_id, created_at DESC);

COMMENT ON TABLE public.document_status_history IS
    'История переходов статусов документа: кто, когда и с каким комментарием';

-- Бэкфилл для документов, зарегистрированных до включения журнала: без него
-- карточка старого документа показывала бы пустую историю. Записываем
-- текущее состояние как исходную точку — это честнее, чем выдумывать
-- промежуточные шаги, которых никто не фиксировал.
INSERT INTO public.document_status_history
    (document_id, from_status, to_status, actor_id, comment, created_at)
SELECT d.id,
       NULL,
       d.status,
       d.author_id,
       'Исходное состояние реестра до включения журнала маршрута',
       COALESCE(d.updated_at, d.created_at)
FROM public.document d
WHERE NOT EXISTS (
    SELECT 1 FROM public.document_status_history h WHERE h.document_id = d.id
);
