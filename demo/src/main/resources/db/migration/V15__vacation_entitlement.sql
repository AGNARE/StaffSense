-- V15: право на отпуск по сотруднику и году.
--
-- До этой миграции отпуск существовал только как факт: утверждённая записка
-- и отметки в табеле. Сколько дней человеку положено за год и сколько
-- остатка — в схеме не было, поэтому «остаток 14 дней» из макета показать
-- было нечем.
--
-- Начисление живёт отдельной таблицей: это кадровое решение (оклад, стаж,
-- политика компании), а не расчёт из событий. Использование, наоборот,
-- не хранится — оно считается из утверждённых записок, чтобы не появилось
-- второго источника правды.

CREATE TABLE IF NOT EXISTS public.vacation_entitlement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    period_year int NOT NULL,
    entitled_days numeric(5,1) NOT NULL,
    carried_over_days numeric(5,1) NOT NULL DEFAULT 0,
    note character varying(300),
    created_at timestamp NOT NULL,
    CONSTRAINT fk_vacation_entitlement_user FOREIGN KEY (user_id) REFERENCES public.users(id),
    CONSTRAINT ux_vacation_entitlement UNIQUE (user_id, period_year),
    CONSTRAINT vacation_days_positive CHECK (entitled_days >= 0 AND carried_over_days >= 0)
);

CREATE INDEX IF NOT EXISTS idx_vacation_entitlement_year
    ON public.vacation_entitlement (period_year);

COMMENT ON TABLE public.vacation_entitlement IS
    'Право на отпуск: сколько дней положено сотруднику за год и сколько перенесено';
