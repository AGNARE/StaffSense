-- V11: реестр документов (модуль «Документы»).
--
-- До этой миграции раздела документов в бэкенде не было: EmployeeDocuments —
-- это персональные данные сотрудника (ИНН, паспорт), а не реестр документов
-- с номерами, сроками хранения и статусами.
--
-- Сроки хранения задаются типом документа в коде (DocumentType) и здесь
-- хранятся вычисленным значением: реестр должен показывать дату, по которой
-- документ уходит в архив, не пересчитывая её каждый раз.
-- NULL в retention_until означает «хранить постоянно» (трудовые договоры).

CREATE TABLE IF NOT EXISTS public.document (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_number character varying(60) NOT NULL,
    doc_type character varying(30) NOT NULL,
    title character varying(300) NOT NULL,
    summary character varying(500),
    employee_id bigint,
    author_id bigint NOT NULL,
    document_date date NOT NULL,
    retention_until date,
    status character varying(30) NOT NULL,
    created_at timestamp NOT NULL,
    updated_at timestamp,
    CONSTRAINT doc_type_check CHECK (doc_type IN ('ORDER', 'CONTRACT', 'CERTIFICATE')),
    CONSTRAINT doc_status_check CHECK (status IN ('DRAFT', 'ON_APPROVAL', 'APPROVED', 'ARCHIVED')),
    CONSTRAINT fk_doc_employee FOREIGN KEY (employee_id) REFERENCES public.users(id),
    CONSTRAINT fk_doc_author FOREIGN KEY (author_id) REFERENCES public.users(id)
);

-- Номер документа уникален в пределах года: «47-к/2026».
CREATE UNIQUE INDEX IF NOT EXISTS ux_document_reg_number
    ON public.document (reg_number);

CREATE INDEX IF NOT EXISTS idx_document_type_status
    ON public.document (doc_type, status);

CREATE INDEX IF NOT EXISTS idx_document_employee
    ON public.document (employee_id);

-- Реестр часто сортируют по дате и сроку хранения.
CREATE INDEX IF NOT EXISTS idx_document_date
    ON public.document (document_date DESC);

COMMENT ON TABLE public.document IS
    'Реестр документов: приказы, договоры, справки (FR-018, реестр и архив)';
