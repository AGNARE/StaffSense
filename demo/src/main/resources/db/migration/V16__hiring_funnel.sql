-- V16: воронка найма — вакансии и кандидаты.
--
-- В системе был кадровый учёт уже нанятых людей, но не было того, что
-- происходит до найма: вакансия открыта, кандидат идёт по этапам.
-- Поэтому «воронка найма» из макета показывать было нечем.

CREATE TABLE IF NOT EXISTS public.vacancy (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title character varying(200) NOT NULL,
    department character varying(100) NOT NULL,
    grade_level character varying(20),
    status character varying(20) NOT NULL,
    openings int NOT NULL DEFAULT 1,
    created_by bigint,
    created_at timestamp NOT NULL,
    opened_at timestamp,
    closed_at timestamp,
    CONSTRAINT vacancy_status_check CHECK (status IN ('DRAFT', 'OPEN', 'ON_HOLD', 'CLOSED')),
    CONSTRAINT vacancy_openings_positive CHECK (openings > 0),
    CONSTRAINT fk_vacancy_author FOREIGN KEY (created_by) REFERENCES public.users(id)
);

CREATE INDEX IF NOT EXISTS idx_vacancy_status ON public.vacancy (status);

CREATE TABLE IF NOT EXISTS public.candidate (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vacancy_id bigint NOT NULL,
    full_name character varying(200) NOT NULL,
    email character varying(150),
    stage character varying(20) NOT NULL,
    source character varying(60),
    applied_at timestamp NOT NULL,
    stage_changed_at timestamp,
    notes character varying(500),
    CONSTRAINT candidate_stage_check CHECK (stage IN
        ('APPLIED', 'SCREENING', 'INTERVIEW', 'OFFER', 'HIRED', 'REJECTED')),
    CONSTRAINT fk_candidate_vacancy FOREIGN KEY (vacancy_id) REFERENCES public.vacancy(id)
);

CREATE INDEX IF NOT EXISTS idx_candidate_vacancy ON public.candidate (vacancy_id);
CREATE INDEX IF NOT EXISTS idx_candidate_stage ON public.candidate (stage);

COMMENT ON TABLE public.vacancy IS 'Вакансия: что ищем, где и сколько человек';
COMMENT ON TABLE public.candidate IS 'Кандидат и его этап воронки найма';
