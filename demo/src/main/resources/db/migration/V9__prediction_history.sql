-- V9: история прогнозов увольнений.
--
-- Зачем. BR-010 хранит у сотрудника ОДИН актуальный прогноз и удаляет прежние,
-- поэтому:
--   * нельзя построить тренд «риск растёт третий месяц»;
--   * нельзя выгрузить прогнозы «за квартал» — остаётся только последний срез;
--   * нельзя проверить, сбывались ли прогнозы (нет снимка на дату).
--
-- Эта таблица — append-only журнал: каждая строка это снимок прогноза на момент
-- расчёта. Текущий прогноз по-прежнему лежит в attrition_predictions и ведёт
-- себя как раньше (BR-010 не меняется), история пишется параллельно.
--
-- Источник (source) нужен, чтобы отличить расчёт ML-сервисом от эвристики,
-- когда ML недоступен: смешивать их в отчётах нельзя.

CREATE TABLE IF NOT EXISTS public.attrition_prediction_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    computed_at timestamp NOT NULL,
    risk_score double precision NOT NULL,
    risk_level character varying(20) NOT NULL,
    source character varying(20) NOT NULL,
    computed_by_id bigint,
    features_snapshot_json text,
    top_risk_factors_json text,
    CONSTRAINT aph_risk_score_range CHECK (risk_score >= 0 AND risk_score <= 100),
    -- Простой IN вместо (col)::text = ANY(ARRAY[...]::text[]): та форма —
    -- вывод pg_dump, она нечитаема и не переносится на другие СУБД.
    CONSTRAINT aph_risk_level_check CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT aph_source_check CHECK (source IN ('ML', 'HEURISTIC', 'SEED')),
    CONSTRAINT fk_aph_user FOREIGN KEY (user_id) REFERENCES public.users(id),
    CONSTRAINT fk_aph_computed_by FOREIGN KEY (computed_by_id) REFERENCES public.users(id)
);

-- Основной сценарий: история сотрудника по убыванию даты.
CREATE INDEX IF NOT EXISTS idx_aph_user_computed
    ON public.attrition_prediction_history (user_id, computed_at DESC);

-- Выгрузка и администрирование: выборка за период по всем сотрудникам.
CREATE INDEX IF NOT EXISTS idx_aph_computed_at
    ON public.attrition_prediction_history (computed_at);

CREATE INDEX IF NOT EXISTS idx_aph_risk_level
    ON public.attrition_prediction_history (risk_level);
