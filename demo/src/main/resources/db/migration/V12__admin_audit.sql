-- V12: журнал действий администратора.
--
-- Администратор может создать учётную запись, сменить роль, заблокировать
-- доступ и сбросить пароль. Без следа такие действия невозможно разобрать
-- постфактум, поэтому пишем их отдельной таблицей.
--
-- Пишем и актора, и цель снимком (email на момент действия): пользователя
-- могут переименовать или удалить, а вопрос «кто это сделал» должен
-- оставаться отвечаемым.

CREATE TABLE IF NOT EXISTS public.admin_audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id bigint,
    actor_email character varying(150),
    action character varying(40) NOT NULL,
    target_id bigint,
    target_email character varying(150),
    details character varying(500),
    created_at timestamp NOT NULL,
    CONSTRAINT admin_audit_action_check CHECK (action IN (
        'USER_CREATED', 'ROLE_CHANGED', 'ACTIVE_CHANGED', 'PASSWORD_RESET'
    ))
);

CREATE INDEX IF NOT EXISTS idx_admin_audit_created
    ON public.admin_audit_log (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_admin_audit_actor
    ON public.admin_audit_log (actor_id);

COMMENT ON TABLE public.admin_audit_log IS
    'Журнал действий администратора: создание, роль, блокировка, сброс пароля';
