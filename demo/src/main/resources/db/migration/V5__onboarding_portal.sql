-- V5: внутренний портал онбординга (модуль B).
--
-- Внутренний справочник компании: ценности, структура, должностные инструкции,
-- регламенты, FAQ и чек-лист новичка. Доступ на чтение — любой сотрудник,
-- на редактирование — HR/ADMIN.
--
-- ВАЖНО: справочник сотрудников реализован отдельным эндпоинтом /directory
-- и НЕ использует /employees (там оклады, KPI и прогнозы риска).

-- ── Статьи портала ───────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.onboarding_article (
    id bigint NOT NULL,
    -- ABOUT / STRUCTURE / RESPONSIBILITIES / POLICIES / FAQ / CHECKLIST
    section character varying(30) NOT NULL,
    title character varying(200) NOT NULL,
    content text,
    order_index integer NOT NULL DEFAULT 0,
    published boolean NOT NULL DEFAULT true,
    updated_by_id bigint,
    updated_at timestamp(6) without time zone
);

ALTER TABLE public.onboarding_article
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.onboarding_article_id_seq
        START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
    );

ALTER TABLE ONLY public.onboarding_article
    ADD CONSTRAINT onboarding_article_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.onboarding_article
    ADD CONSTRAINT fk_onboarding_article_updated_by
    FOREIGN KEY (updated_by_id) REFERENCES public.users(id);

CREATE INDEX IF NOT EXISTS idx_onboarding_article_section
    ON public.onboarding_article (section, order_index);

-- ── Отметки чек-листа новичка ────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.onboarding_checklist_progress (
    id bigint NOT NULL,
    user_id bigint NOT NULL,
    article_id bigint NOT NULL,
    completed_at timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.onboarding_checklist_progress
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.onboarding_checklist_progress_id_seq
        START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
    );

ALTER TABLE ONLY public.onboarding_checklist_progress
    ADD CONSTRAINT onboarding_checklist_progress_pkey PRIMARY KEY (id);

-- Один пункт отмечается сотрудником один раз.
ALTER TABLE ONLY public.onboarding_checklist_progress
    ADD CONSTRAINT uq_onboarding_progress_user_article UNIQUE (user_id, article_id);

ALTER TABLE ONLY public.onboarding_checklist_progress
    ADD CONSTRAINT fk_onboarding_progress_user
    FOREIGN KEY (user_id) REFERENCES public.users(id);
ALTER TABLE ONLY public.onboarding_checklist_progress
    ADD CONSTRAINT fk_onboarding_progress_article
    FOREIGN KEY (article_id) REFERENCES public.onboarding_article(id);

CREATE INDEX IF NOT EXISTS idx_onboarding_progress_user
    ON public.onboarding_checklist_progress (user_id);
