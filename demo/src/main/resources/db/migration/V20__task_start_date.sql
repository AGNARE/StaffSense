-- V20: плановая дата старта задачи.
--
-- План-график строил полосу от createdAt до dueDate: это фактический срок,
-- а не план. Для «план / факт» нужна отдельная дата старта — она не выводится
-- из других полей, поэтому хранится явно.
--
-- Колонка nullable: у существующих задач плана нет, и придумывать его
-- задним числом нельзя.

ALTER TABLE public.tasks ADD COLUMN IF NOT EXISTS start_date date;

COMMENT ON COLUMN public.tasks.start_date IS
    'Плановая дата старта; null — план не задан (полоса строится от даты создания)';
