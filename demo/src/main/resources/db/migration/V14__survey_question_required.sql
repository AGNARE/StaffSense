-- V14: признак обязательности вопроса опроса (экран «Конструктор опроса»).
--
-- Зачем: конструктор позволяет отметить вопрос обязательным или необязательным,
-- и признак должен переживать сохранение черновика — иначе обязательность,
-- которую HR выбрал в форме, терялась бы после перезагрузки страницы.
--
-- DEFAULT true сохраняет прежнее поведение: все уже существующие вопросы
-- считаются обязательными, поэтому прохождение опросов не меняется.
--
-- ADD COLUMN IF NOT EXISTS делает миграцию идемпотентной, как и остальные
-- миграции проекта: повторный запуск на базе, где колонка уже есть, не падает.

ALTER TABLE public.survey_questions
    ADD COLUMN IF NOT EXISTS is_required boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN public.survey_questions.is_required IS
    'Обязательность ответа: необязательный вопрос можно пропустить (FR-022)';
