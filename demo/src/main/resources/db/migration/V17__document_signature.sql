-- V17: подпись документа и срок подписи (SLA).
--
-- До этой миграции маршрут документа знал только текущий статус: вопрос
-- «кто подписал, когда и с каким решением» ответа не имел, а срока
-- согласования не существовало вовсе — просроченный документ ничем не
-- отличался от только что отправленного на подпись.
--
-- Решение по подписи — отдельная сущность, а не поле документа: подписей у
-- одного документа может быть несколько (руководитель и кадровая служба),
-- и каждая должна остаться в реестре со своим комментарием и временем.
--
-- due_at — срок подписи. Ставится при переходе в «На согласовании»
-- (DocumentSignatureService, SLA из documents.signature.sla-hours) и
-- очищается, когда документ покидает этот шаг. Просрочка — сигнал, а не
-- действие: по due_at никто не меняет статусы автоматически.

ALTER TABLE public.document
    ADD COLUMN IF NOT EXISTS due_at timestamp;

-- Очередь на подпись и планировщик просрочки делают один и тот же выбор:
-- «на согласовании» + фильтр/сортировка по сроку.
CREATE INDEX IF NOT EXISTS idx_document_status_due_at
    ON public.document (status, due_at);

CREATE TABLE IF NOT EXISTS public.document_signature (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL,
    signer_id bigint NOT NULL,
    decision character varying(20) NOT NULL,
    comment character varying(500),
    signed_at timestamp NOT NULL,
    created_at timestamp NOT NULL,
    CONSTRAINT doc_signature_decision_check CHECK (decision IN ('APPROVED', 'REJECTED')),
    CONSTRAINT fk_doc_signature_document FOREIGN KEY (document_id)
        REFERENCES public.document(id) ON DELETE CASCADE,
    CONSTRAINT fk_doc_signature_signer FOREIGN KEY (signer_id)
        REFERENCES public.users(id)
);

-- Один человек подписывает документ один раз: повторная подпись — не
-- «вторая подпись», а ошибка клиента (двойной клик, повтор запроса).
-- Сервис отдаёт на это 409; индекс не даёт обойти проверку в обход API.
CREATE UNIQUE INDEX IF NOT EXISTS ux_document_signature_document_signer
    ON public.document_signature (document_id, signer_id);

-- Карточка читает подписи одного документа в хронологическом порядке.
CREATE INDEX IF NOT EXISTS idx_document_signature_document
    ON public.document_signature (document_id, signed_at DESC);

COMMENT ON TABLE public.document_signature IS
    'Подписи документа: кто, когда, решение (APPROVED/REJECTED) и комментарий';

COMMENT ON COLUMN public.document.due_at IS
    'Срок подписи (SLA); NULL — документ не ждёт подписи';

-- Бэкфилл: документы, которые уже стоят на согласовании, получают срок от
-- момента последнего изменения (24 часа — дефолт SLA). Если этот срок уже
-- прошёл, документ сразу попадает в просроченные: это честный сигнал о том,
-- что подпись заждалась, а не выдуманная дата в будущем.
UPDATE public.document
SET due_at = COALESCE(updated_at, created_at) + interval '24 hours'
WHERE status = 'ON_APPROVAL'
  AND due_at IS NULL;
