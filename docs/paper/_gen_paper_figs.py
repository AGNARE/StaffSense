def no_split(table_):
    """Держать таблицу целиком на одной странице.

    cantSplit запрещает разрыв строки, а keep_with_next на всех строках, кроме
    последней, не даёт Word разорвать саму таблицу: она переезжает целиком.
    """
    rows = table_.rows
    for row in rows:
        row._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))
    for row in rows[:-1]:
        for cell in row.cells:
            for paragraph in cell.paragraphs:
                paragraph.paragraph_format.keep_with_next = True
    return table_


