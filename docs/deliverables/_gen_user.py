_para = gost.para


def para(doc, text, **kwargs):
    kwargs.setdefault("space_after", 2)
    return _para(doc, text, **kwargs)


gost.para = para


def steps(doc, items):
    for index, item in enumerate(items, start=1):
        gost.para(doc, f"{index}. {item}", indent=False, space_after=2)


def expect(doc, text):
    """Ожидаемый результат сценария — отдельным абзацем."""
    gost.para(doc, text, indent=False, space_after=6)


def small_table(doc, header, rows, widths, caption, size=10.5):
    gost.table(doc, header, rows, widths=widths, caption=caption,
               font_size=Pt(size))


def figure(doc, name, caption, width=14.5):
    gost.figure(doc, str(IMG / name), caption, width_cm=width)


