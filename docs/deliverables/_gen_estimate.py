# --------------------------------------------------------------------------
# Форматирование чисел: тысячи — пробел, дробная часть — запятая
# --------------------------------------------------------------------------


def n(value, digits=2):
    """1285 -> '1 285', 844687.5 -> '844 687,50'."""
    quant = Decimal(1).scaleb(-digits)
    rounded = Decimal(str(value)).quantize(quant, rounding=ROUND_HALF_UP)
    text = f"{rounded:,.{digits}f}"
    # Минус — типографский (U+2212), а не дефис: в формулах он уже такой.
    return text.replace(",", " ").replace(".", ",").replace("-", "\u2212")


