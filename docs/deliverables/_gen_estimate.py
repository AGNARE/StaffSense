# --------------------------------------------------------------------------
# Жёсткая раскладка таблиц.
#
# _gost.table проставляет ширины ячеек, но оставляет tblLayout = autofit,
# и Word пересчитывает колонки как равные: длинный текст в узкой колонке
# растягивает строки, документ раздувается втрое. Здесь раскладка
# фиксируется (tblLayout=fixed, tblW, tblGrid) — модуль не переписывается.
# --------------------------------------------------------------------------


def _fixed_layout(t, widths_cm):
    tbl = t._tbl
    t.autofit = False
    tblPr = tbl.tblPr

    tblW = tblPr.find(qn("w:tblW"))
    if tblW is None:
        tblW = OxmlElement("w:tblW")
        tblPr.append(tblW)
    tblW.set(qn("w:type"), "dxa")
    tblW.set(qn("w:w"), str(int(Cm(sum(widths_cm)).twips)))

    for old in tblPr.findall(qn("w:tblLayout")):
        tblPr.remove(old)
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    tblPr.append(layout)

    grid = tbl.tblGrid
    for col, width in zip(grid.findall(qn("w:gridCol")), widths_cm):
        col.set(qn("w:w"), str(int(Cm(width).twips)))

    for row in t.rows:
        for cell, width in zip(row.cells, widths_cm):
            cell.width = Cm(width)


def table(doc, header, rows, *, widths=None, caption=None, font_size=SMALL):
    result = _gost_table(doc, header, rows, widths=widths, caption=caption,
                         font_size=font_size)
    if widths:
        _fixed_layout(result, widths)
    return result


