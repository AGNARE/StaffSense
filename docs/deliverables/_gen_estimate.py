DISCOUNT = 0.12


def npv(s):
    """NPV за три года: дисконтированный чистый эффект минус капитальные затраты."""
    return sum(s["net"] / (1 + DISCOUNT) ** year for year in (1, 2, 3)) - COST_DEV


