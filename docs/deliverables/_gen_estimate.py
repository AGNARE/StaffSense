def dpb(s):
    """Дисконтированный срок окупаемости в месяцах; None, если не окупается за 3 года."""
    rate = (1 + DISCOUNT) ** (1 / 12)
    accumulated = 0.0
    for month in range(1, 37):
        accumulated += s["net"] / 12 / rate ** month
        if accumulated >= COST_DEV:
            return month
    return None


