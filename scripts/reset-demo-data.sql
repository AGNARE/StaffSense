-- reset-demo-data.sql — очистка демо-базы от следов QA-прогонов.
--
-- ЧТО ДЕЛАЕТ
--   Удаляет только тестовый мусор, оставленный прогонами агентов, и не
--   трогает демо-набор: сотрудников, проекты, задачи демо-сценария, опросы,
--   KPI, нагрузку, прогнозы и порталы. Признаки удаления перечислены явно
--   и только по ним:
--     1) задачи, название которых начинается с "QA-";
--     2) служебные записки, причина которых начинается с "QA-";
--     3) вакансии с названием "Аудит-вакансия" (сначала их кандидаты —
--        внешнего ключа с ON DELETE CASCADE у candidate нет);
--     4) документы, в названии которых есть "Live-" или "????"
--        ("????" — искажённая кириллица из live-прогонов, например
--        "Live-???????? ??????? (V17)").
--
--   Дочерние строки документов (public.document_status_history,
--   public.document_signature) удаляются каскадом, объявленным в миграциях
--   V13 и V17, — отдельного DELETE не требуется.
--
-- ЧЕГО НЕ ДЕЛАЕТ
--   Пользователей с почтой на @test.local скрипт не удаляет: на них держатся
--   тесты. Также он не сбрасывает всю базу и не пересоздаёт демо-данные —
--   для полного сброса есть пересев через DataInitializer на пустой базе.
--
-- КАК ЗАПУСКАТЬ (только демо-стенд)
--   psql -h localhost -p 5433 -U postgres -d db_staff_sense -f scripts/reset-demo-data.sql
--
--   Скрипт идемпотентен: повторный запуск просто не найдёт строк. Все удаления
--   идут одной транзакцией — при ошибке база останется как была.
--
-- ВНИМАНИЕ
--   Предназначен ТОЛЬКО для демонстрационного стенда. На рабочей базе
--   признаки могут совпасть с настоящими данными, а удаление необратимо.
--   Стенд общий: перед запуском предупредите других QA-агентов, которые
--   в этот момент работают на :9091.

-- Файл в UTF-8, а в нём кириллические литералы ('Аудит-вакансия'):
-- на Windows psql по умолчанию может ждать другую кодировку.
SET client_encoding = 'UTF8';

BEGIN;

-- 1. Задачи, созданные прогонами: префикс "QA-" в названии.
DELETE FROM public.tasks
 WHERE title ILIKE 'qa-%';

-- 2. Служебные записки прогонов: причина начинается с "QA-".
DELETE FROM public.service_memo
 WHERE reason ILIKE 'qa-%';

-- 3. Вакансии "Аудит-вакансия" и их кандидаты (FK без каскада).
DELETE FROM public.candidate
 WHERE vacancy_id IN (
     SELECT id FROM public.vacancy WHERE title = 'Аудит-вакансия'
 );

DELETE FROM public.vacancy
 WHERE title = 'Аудит-вакансия';

-- 4. Документы live-прогонов: "Live-" в названии либо литерал "????".
--    ILIKE — чтобы не зависеть от регистра префикса.
DELETE FROM public.document
 WHERE title ILIKE '%live-%'
    OR title LIKE '%????%';

COMMIT;
